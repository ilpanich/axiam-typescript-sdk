function implicitParams(namespace, op) {
  const names = new Set(op.path_params.map((p) => p.name));
  const out = new Set();
  if (names.has('org_id')) out.add('org_id');
  if (names.has('tenant_id') && IMPLICIT_TENANT_NAMESPACES.has(namespace)) out.add('tenant_id');
  return out;
}

function responseType(op, secrets) {
  const { kind, schema } = op.response;
  if (kind === 'none') return { public: 'void', wire: 'void', kind };
  const pub = `models.${pascal(schema)}`;
  const wire = secrets.has(schema) ? `models.${pascal(schema)}Wire` : pub;
  if (kind === 'array') return { public: `${pub}[]`, wire: `${wire}[]`, kind };
  if (kind === 'page') return { public: `Page<${pub}>`, wire: `Page<${wire}>`, kind };
  return { public: pub, wire, kind };
}

function emitNamespace(namespace, nsdef, secrets) {
  // `Api` suffix: `EmailConfig` is both a namespace and a schema name, and a
  // future schema could collide with any other namespace. Suffixing the handle
  // keeps `export *` from both modules unambiguous.
  const cls = `${pascal(namespace)}Api`;
  const ops = nsdef.operations;
  const hasOrg = Object.values(ops).some((o) => implicitParams(namespace, o).has('org_id'));
  const hasTenant = Object.values(ops).some((o) => implicitParams(namespace, o).has('tenant_id'));

  const body = [];
  const filters = emitFilters(namespace, nsdef);
  if (filters) body.push(filters);

  body.push(
    ...doc(
      `The \`${namespace}\` namespace handle.\n\n${nsdef.doc}\n\nAcquiring one performs no I/O and allocates nothing meaningful (§27.2 rule 1); it holds the client and cannot be constructed without one.`,
    ),
  );
  body.push(`export class ${cls} {`);
  body.push('  readonly #client: AxiamClient;');
  body.push('  readonly #scope: NamespaceScope;');
  body.push('');
  body.push('  /** @internal — reached through `client.<namespace>`, never constructed directly. */');
  body.push('  constructor(client: AxiamClient, scope: NamespaceScope = {}) {');
  body.push('    this.#client = client;');
  body.push('    this.#scope = scope;');
  body.push('  }');
  body.push('');
  if (hasOrg) {
    body.push(
      ...doc(
        'Address a different organization than the client\'s own.\n\n§27.4 rule 3: the client\'s `orgId` is the default, and a platform-admin token legitimately overrides it. Returns a new handle; the original is unchanged.',
        '  ',
      ),
    );
    body.push(`  inOrg(orgId: string): ${cls} {`);
    body.push(`    return new ${cls}(this.#client, { ...this.#scope, orgId });`);
    body.push('  }');
    body.push('');
  }
  if (hasTenant) {
    body.push(
      ...doc(
        "Address a different tenant than the client's own (§27.4 rule 3).\n\nReturns a new handle; the original is unchanged.",
        '  ',
      ),
    );
    body.push(`  forTenant(tenantId: string): ${cls} {`);
    body.push(`    return new ${cls}(this.#client, { ...this.#scope, tenantId });`);
    body.push('  }');
    body.push('');
  }

  for (const [opname, op] of Object.entries(ops)) {
    body.push(emitOperation(namespace, opname, op, secrets));
  }
  body.push('}');

  const rendered = body.join('\n');
  const imports = [
    "import type { AxiamClient } from '../../rest/client.js';",
    "import * as models from '../models.js';",
  ];
  if (/\bPage\b/.test(rendered)) imports.push("import type { Page, PageRequest } from '../page.js';");
  const pageValues = ['collectPages', 'pageQuery'].filter((n) => new RegExp(`\\b${n}\\b`).test(rendered));
  if (pageValues.length) imports.push(`import { ${pageValues.join(', ')} } from '../page.js';`);
  imports.push("import { sendManagement } from '../request.js';");
  imports.push("import type { NamespaceScope } from '../scope.js';");
  if (/\bchecks\./.test(rendered)) imports.push("import * as checks from '../checks.js';");
  if (/resolveOrg|resolveTenant/.test(rendered)) {
    imports.push("import { resolveOrg, resolveTenant } from '../scope.js';");
  }

  return [
    BANNER,
    `/**`,
    ` * The \`${namespace}\` management namespace (CONTRACT §27.1).`,
    ` *`,
    ...wrap(nsdef.doc).map((l) => (l ? ` * ${l}` : ' *')),
    ` */`,
    '',
    imports.join('\n'),
    '',
    rendered,
    '',
  ].join('\n');
}

/**
 * Query parameters that become method arguments, rather than `PageRequest`.
 *
 * `offset` and `limit` have always come from `PageRequest`. `search` joins them
 * on paginated operations (CONTRACT §27.4 rule 4): the term is part of which
 * page this is, and putting it on the page request rather than on each of the
 * twenty generated `list` methods is what makes `collectPages` carry it across
 * the whole walk instead of filtering only the first request.
 *
 * The `paginated` guard matters. A *non*-paginated operation that grew a
 * `search` parameter would have no `PageRequest` to carry it, so it keeps its
 * own argument — none exists in the registry today, and this is what keeps that
 * from silently dropping the parameter if one ever does.
 */
function extraQueryParams(op) {
  const owned = op.paginated ? ['offset', 'limit', 'search'] : ['offset', 'limit'];
  return op.query_params.filter((q) => !owned.includes(q.name));
}

/**
 * Schema name -> the fields a list projection adds on top of it.
 *
 * `certificates.list` answers `Certificate` plus `bound_service_account_id`, a
 * graph edge the server resolves for the whole page in one query. CONTRACT
 * §27.11 rule 4 lets an SDK carry that as an optional field on the base type,
 * which is what this does: the field is absent on `get`, and the SDK never
 * synthesizes it there with a second request.
 */
function projectionMap() {
  const out = new Map();
  for (const nsdef of Object.values(REGISTRY.namespaces)) {
    for (const op of Object.values(nsdef.operations)) {
      const adds = op.response.projected_fields;
      if (!adds || !op.response.schema) continue;
      const base = op.response.schema.replace(/^\[\]/, '');
      out.set(base, [...(out.get(base) ?? []), ...adds]);
    }
  }
  return out;
}

function emitFilters(namespace, nsdef) {
  const out = [];
  for (const [opname, op] of Object.entries(nsdef.operations)) {
    const optional = extraQueryParams(op).filter((q) => !q.required);
    if (optional.length <= 2) continue;
    const name = `${pascal(namespace)}${pascal(opname)}Filter`;
    out.push(
      ...doc(
        `Optional filters for \`${namespace}.${opname}\`.\n\nSix loose optional arguments is a call site a reader cannot check and a refactor silently reorders, so they travel as one object.`,
      ),
    );
    out.push(`export interface ${name} {`);
    for (const q of optional) {
      out.push(...doc(`Filter on \`${q.name}\`.`, '  '));
      out.push(`  ${camel(q.name)}?: string;`);
    }
    out.push('}');
    out.push('');
  }
  return out.join('\n');
}

function emitOperation(namespace, opname, op, secrets) {
  const canonical = `${namespace}.${opname}`;
  const implicit = implicitParams(namespace, op);
  const method = camel(opname);
  const args = [];
  const prelude = [];
  let route = op.path;

  for (const p of op.path_params) {
    if (implicit.has(p.name)) {
      const fn = p.name === 'org_id' ? 'resolveOrg' : 'resolveTenant';
      const local = camel(p.name);
      prelude.push(
        `    const ${local} = ${fn}(this.#client, this.#scope, ${JSON.stringify(canonical)});`,
      );
      route = route.replace(`{${p.name}}`, `\${${local}}`);
    } else {
      args.push(`${camel(p.name)}: string`);
      route = route.replace(`{${p.name}}`, `\${encodeURIComponent(${camel(p.name)})}`);
    }
  }

  const extra = extraQueryParams(op);
  const requiredQ = extra.filter((q) => q.required);
  const optionalQ = extra.filter((q) => !q.required);
  const filterType =
    optionalQ.length > 2 ? `${pascal(namespace)}${pascal(opname)}Filter` : null;
  for (const q of requiredQ) args.push(`${camel(q.name)}: string`);
  if (filterType) args.push(`filter: ${filterType} = {}`);
  else for (const q of optionalQ) args.push(`${camel(q.name)}?: string`);
  if (op.paginated) args.push('page: PageRequest = {}');

  let bodyExpr = 'undefined';
  if (op.request_body === 'schema') {
    const schema = op.request_schema;
    args.push(`body: models.${pascal(schema)}`);
    bodyExpr = secrets.has(schema) ? `models.${camel(pascal(schema))}ToWire(body)` : 'body';
    // CONTRACT.md §5.2.3 rule 1 — see `omitEmptyTenantScope`. Applied at the
    // call site rather than inside `sendManagement` so it is visible in the
    // generated code that a body is being normalised, and so it costs nothing
    // on the operations that have no such field.
    if (SCHEMAS[schema]?.properties?.tenant_scope) {
      bodyExpr = `models.omitEmptyTenantScope(${bodyExpr})`;
    }
    // CONTRACT.md §27.13 / CONTRACT 1.52 N3 (C-12): refuse client-side,
    // before any request, a request-body array field typed as an
    // externally-tagged union (SubjectAltName's `{dns}|{ip}` shape) whose
    // element names neither or both of its keys. See EXTERNALLY_TAGGED's
    // doc comment for why the type alone cannot stop this.
    for (const [prop, propSchema] of Object.entries(SCHEMAS[schema]?.properties ?? {})) {
      const types = Array.isArray(propSchema?.type) ? propSchema.type : [propSchema?.type];
      const itemsRef = types.includes('array') ? propSchema?.items?.$ref : undefined;
      const target = itemsRef ? EXTERNALLY_TAGGED.get(itemsRef.split('/').pop()) : undefined;
      if (target) {
        prelude.push(`    models.assertValid${target.rname}List(body.${prop});`);
      }
      // CONTRACT §31.2 — see OPEN_TAGGED_UNIONS.
      const directRef = propSchema?.$ref?.split('/').pop();
      if (directRef && OPEN_TAGGED_UNIONS.has(directRef)) {
        prelude.push(`    models.assertKnown${pascal(directRef)}(body.${prop});`);
      }
    }
  } else if (op.request_body === 'untyped') {
    args.push('body: unknown');
    bodyExpr = 'body';
  }
  if (PRECHECKS[canonical]) {
    prelude.unshift(`    checks.${PRECHECKS[canonical]}(body);`);
  }

  const queryEntries = [];
  if (op.paginated) queryEntries.push('...pageQuery(page)');
  for (const q of requiredQ) queryEntries.push(`${JSON.stringify(q.name)}: ${camel(q.name)}`);
  for (const q of optionalQ) {
    const src = filterType ? `filter.${camel(q.name)}` : camel(q.name);
    queryEntries.push(`'${q.name}': ${src}`);
  }

  const resp = responseType(op, secrets);
  const lines = doc(buildOperationDoc(op, canonical), '  ');
  lines.push(`  async ${method}(${args.join(', ')}): Promise<${resp.public}> {`);
  lines.push(...prelude);
  const wireGeneric = resp.kind === 'none' ? 'void' : resp.wire;
  lines.push(`    ${resp.kind === 'none' ? '' : 'const wire = '}await sendManagement<${wireGeneric}>(this.#client, {`);
  const q = (v) => `'${v}'`;
  lines.push(`      operation: ${q(canonical)},`);
  lines.push(`      method: ${q(op.method)},`);
  lines.push(`      pathTemplate: ${q(op.path)},`);
  // A template literal with nothing to interpolate is noise.
  lines.push(`      path: ${route.includes('${') ? `\`${route}\`` : q(route)},`);
  if (queryEntries.length) lines.push(`      query: { ${queryEntries.join(', ')} },`);
  if (bodyExpr !== 'undefined') lines.push(`      body: ${bodyExpr},`);
  lines.push('    });');

  const scrub = resp.kind !== 'none' && SCRUBBABLE.has(op.response.schema)
    ? `models.scrub${pascal(op.response.schema)}`
    : null;
  if (scrub && resp.wire !== resp.public) {
    throw new Error(`${canonical}: a response both scrubbed and carrying Sensitive fields is not supported`);
  }
  if (resp.kind === 'none') {
    // nothing to return
  } else if (scrub) {
    if (resp.kind === 'array') lines.push(`    return wire.map(${scrub});`);
    else if (resp.kind === 'page') {
      // The envelope keeps only `Page`'s own members too (§34.2 P12.1).
      lines.push(
        `    return { items: wire.items.map(${scrub}), total: wire.total, offset: wire.offset, limit: wire.limit };`,
      );
    } else lines.push(`    return ${scrub}(wire);`);
  } else if (resp.wire === resp.public) {
    lines.push('    return wire;');
  } else {
    const conv = `models.${camel(pascal(op.response.schema))}FromWire`;
    if (resp.kind === 'array') lines.push(`    return wire.map(${conv});`);
    else if (resp.kind === 'page') {
      lines.push(`    return { ...wire, items: wire.items.map(${conv}) };`);
    } else lines.push(`    return ${conv}(wire);`);
  }
  lines.push('  }');
  lines.push('');

  if (op.paginated) {
    const lead = args.filter((a) => !a.startsWith('page:'));
    const forward = lead.map((a) => a.split(/[:=]/)[0].trim());
    lines.push(
      ...doc(
        `Walk \`${canonical}\` to exhaustion, concatenating every page.\n\nThe auto-paging form §27.4 rule 4 requires. It stops on an empty page even if \`total\` disagrees, so a misreporting server costs one wasted request rather than an unbounded loop.`,
        '  ',
      ),
    );
    const inner = resp.public.slice('Page<'.length, -1);
    lines.push(
      `  ${method}All(${[...lead, 'start: PageRequest = {}'].join(', ')}): Promise<${inner}[]> {`,
    );
    lines.push(
      `    return collectPages(start, (p) => this.${method}(${[...forward, 'p'].join(', ')}));`,
    );
    lines.push('  }');
    lines.push('');
  }
  return lines.join('\n');
}

function buildOperationDoc(op, canonical) {
  let text = `\`${op.method} ${op.path}\``;
  if (CALL_SITE_NOTES[canonical]) text += `\n\n${CALL_SITE_NOTES[canonical]}`;
  if (op.update_style === 'replace') {
    // Only a body whose every member is required may say so (R-28): a
    // replacement overwrites what it leaves out, it does not make an optional
    // member mandatory.
    const { props, required } = flatten(op.request_schema);
    const allRequired = Object.keys(props).every((p) => required.has(p));
    text += allRequired
      ? '\n\n**This is a replacement, not a patch** (§27.4 rule 5). Every field of the body is required, and what you do not carry over from a prior read is not preserved — it is overwritten. Read first, change the field you mean, send the whole thing back.'
      : '\n\n**This is a replacement, not a patch** (§27.4 rule 5). Only the required members must be set, but what you do not carry over from a prior read is not preserved: an optional member left out is overwritten with its default, not kept (except where noted above). Read first, change the field you mean, send the whole thing back.';
  }
  if (op.sensitive_response_fields.length) {
    text += `\n\n**Returns secret material, once.** \`${op.sensitive_response_fields.join(
      ', ',
    )}\` is returned by this call and by no other; no later \`get\` will return it again, and the \`get\` projection has no field where it was. Discarding the result destroys the credential (§27.5 rule 3).`;
  }
  if (op.method !== 'GET') {
    text +=
      '\n\nNot retried on failure (§27.4 rule 8): every write on this surface is issued exactly once, including the ones that look idempotent.';
  }
  return text;
}

