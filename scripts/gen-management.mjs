function emitModels() {
  const secrets = sensitiveMap();
  const directions = wireDirections();
  const out = [
    BANNER,
    `
/**
 * Request and response types for the CONTRACT §27 management surface.
 *
 * Three shapes recur and are worth knowing before reading:
 *
 * - **Sparse update bodies.** Every field is optional, and an omitted field is
 *   *absent from the wire body* rather than sent as \`null\` — so a body
 *   carrying one field changes one field (§27.4 rule 5). This SDK cannot
 *   express "set this field to null", which is the safe direction to be
 *   inexpressive in.
 * - **Replacement bodies.** \`SetOrgSettings\`, the organization email config,
 *   \`WebauthnAttestationPolicy\` and \`SetMtlsTrustAnchor\` have required
 *   fields, because a \`PUT\` on those routes replaces rather than patches.
 *   TypeScript will not let you build one half-filled, which is the point.
 * - **Types carrying a secret.** These hold a {@link Sensitive} and come with
 *   a private wire twin, because \`Sensitive.toJSON()\` returns
 *   \`"[SENSITIVE]"\` — serializing the public type directly would send the
 *   placeholder to the server, and deserializing into it would leave the
 *   secret an ordinary string.
 */
import { Sensitive } from '../core/sensitive.js';

/**
 * Drops a \`tenant_scope\` that names no tenants.
 *
 * CONTRACT.md §5.2.3 rule 1: the server refuses \`tenant_scope: []\` with
 * \`400\`. An assignment reaching no tenant contributes nothing anywhere, so it
 * is a grant that does not exist rather than a restriction, and the server
 * declines to guess which was meant.
 *
 * \`JSON.stringify\` already drops \`undefined\`, so the absent case needs no
 * help. \`[]\` is the one that does: the natural way to build the field is to
 * collect into an array and pass it, which yields \`[]\` for "no tenants named"
 * and would put the refused shape on the wire. Both spellings of absent
 * therefore travel the same way — by not appearing.
 *
 * Returns the body unchanged when there is nothing to drop, so the common
 * path allocates nothing.
 */
export function omitEmptyTenantScope<T>(body: T): T {
  if (
    body
    && typeof body === 'object'
    && 'tenant_scope' in body
    && Array.isArray((body as { tenant_scope?: unknown }).tenant_scope)
    && (body as { tenant_scope: unknown[] }).tenant_scope.length === 0
  ) {
    const { tenant_scope: _dropped, ...rest } = body as Record<string, unknown>;
    return rest as T;
  }
  return body;
}
`,
  ];

  const projections = projectionMap();
  for (const name of schemaClosure()) {
    const schema = SCHEMAS[name];
    const rname = pascal(name);
    if (schema.enum) {
      out.push(emitEnum(rname, schema));
      continue;
    }
    const union = discriminated(schema);
    if (union) {
      out.push(emitUnion(rname, schema, union));
      continue;
    }
    out.push(
      emitInterface(
        rname,
        name,
        secrets.get(name) ?? new Set(),
        directions.get(name) ?? new Set(),
        projections.get(name) ?? [],
      ),
    );
  }
  return out.join('\n');
}

function emitEnum(rname, schema) {
  const lines = doc(
    (schema.description ?? `\`${rname}\` (generated from openapi.json).`) +
      '\n\nAn **open** enum. The final `(string & {})` arm accepts a value this ' +
      "SDK's copy of the spec does not list, so the next one the server adds " +
      'reaches a caller as itself rather than failing the response it arrived ' +
      'in (CONTRACT §27.11 rule 1). The named arms still autocomplete and still ' +
      'narrow; what the extra arm removes is the illusion that a value outside ' +
      'them cannot occur, which is what an exhaustive `switch` over the named ' +
      'ones quietly assumes.',
  );
  lines.push(`export type ${rname} =`);
  schema.enum.forEach((v) => {
    lines.push(`  | ${JSON.stringify(v)}`);
  });
  // eslint/prettier keep `(string & {})` as written; it is the standard way to
  // widen a literal union without losing completion on the literals.
  lines.push('  // eslint-disable-next-line @typescript-eslint/ban-types');
  lines.push('  | (string & {});');
  lines.push('');
  return lines.join('\n');
}

function emitUnion(rname, schema, { tag, arms }) {
  const lines = doc(
    schema.description ?? `\`${rname}\` — a union discriminated by \`${tag}\`.`,
  );
  lines.push(`export type ${rname} =`);
  arms.forEach(({ value, payload }, i) => {
    const tail = i === arms.length - 1 ? ';' : '';
    const tagDoc = `/** Discriminator: always \`${value}\`. */`;
    if (payload.$ref) {
      lines.push(`  | ({`);
      lines.push(`      ${tagDoc}`);
      lines.push(`      ${tag}: ${JSON.stringify(value)};`);
      lines.push(`    } & ${pascal(payload.$ref.split('/').pop())})${tail}`);
    } else {
      const required = new Set(payload.required ?? []);
      lines.push('  | {');
      lines.push(`      ${tagDoc}`);
      lines.push(`      ${tag}: ${JSON.stringify(value)};`);
      for (const [n, prop] of Object.entries(payload.properties ?? {})) {
        lines.push(...doc(prop.description ?? `\`${n}\`.`, '      '));
        lines.push(`      ${n}${required.has(n) ? '' : '?'}: ${tsType(prop)};`);
      }
      lines.push(`    }${tail}`);
    }
  });
  lines.push('');
  return lines.join('\n');
}

function emitInterface(rname, name, secrets, directions, projected = []) {
  const { props: basePlain, required, description } = flatten(name);
  const props = { ...basePlain };
  const projectedNames = new Set();
  for (const add of projected) {
    if (props[add.name]) continue;
    projectedNames.add(add.name);
    props[add.name] = {
      type: add.type,
      format: add.format,
      description:
        'Resolved by the list projection only.\n\n' +
        'The server resolves this for a whole page in one query, so it is ' +
        'populated by the `list` operation and is absent from `get` ' +
        '(CONTRACT §27.11 rule 4). Absent there means "this read does not ' +
        'carry it", not "there is nothing bound" — the SDK does not issue a ' +
        'second request to fill it in.',
    };
  }
  const owners = new Set([name, ...composedFrom(name)]);
  void owners;
  const fields = Object.entries(props)
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([pname, pschema]) => ({
      name: pname,
      optional: !required.has(pname) || projectedNames.has(pname),
      secret: secrets.has(pname),
      type: secrets.has(pname) ? 'Sensitive<string>' : tsType(pschema),
      description: pschema.description,
    }));

  const allOptional = fields.length > 0 && fields.every((f) => f.optional);
  const lines = doc(
    (description ?? `\`${rname}\` (generated from openapi.json).`) +
      (allOptional
        ? '\n\nEvery field is optional, so this is a **sparse** body: what you leave out is left unchanged, and is omitted from the wire request entirely rather than sent as `null` (§27.4 rule 5).'
        : ''),
  );

  lines.push(`export interface ${rname} {`);
  if (!fields.length) lines.push('  // The server documents no fields on this schema.');
  for (const f of fields) {
    const text = f.description ?? `\`${f.name}\`.`;
    lines.push(
      ...doc(
        f.secret
          ? `${text}\n\n**Secret.** Redacted from every string, log and JSON rendering; call \`.expose()\` to read it.`
          : text,
        '  ',
      ),
    );
    lines.push(`  ${f.name}${f.optional ? '?' : ''}: ${f.type};`);
  }
  lines.push('}');
  lines.push('');

  if (!secrets.size) return lines.join('\n');

  // The wire twin, plus only the conversion direction this type travels in.
  const wire = `${rname}Wire`;
  lines.push(
    ...doc(
      `Wire twin of {@link ${rname}} — plain strings, never logged.\n\n@internal — it exists because \`Sensitive\` cannot be serialized, not because a consumer should read it.`,
    ),
  );
  lines.push(`export interface ${wire} {`);
  for (const f of fields) {
    const type = f.secret ? 'string' : f.type;
    lines.push(`  ${f.name}${f.optional ? '?' : ''}: ${type};`);
  }
  lines.push('}');
  lines.push('');

  if (directions.has('response')) {
    lines.push(...doc(`Wrap the secret fields a \`${rname}\` response carries (§27.5).`));
    lines.push(`export function ${camel(rname)}FromWire(w: ${wire}): ${rname} {`);
    lines.push('  return {');
    lines.push('    ...w,');
    for (const f of fields.filter((x) => x.secret)) {
      lines.push(
        f.optional
          ? `    ${f.name}: w.${f.name} === undefined ? undefined : new Sensitive(w.${f.name}),`
          : `    ${f.name}: new Sensitive(w.${f.name}),`,
      );
    }
    lines.push('  };');
    lines.push('}');
    lines.push('');
  }
  if (directions.has('request')) {
    lines.push(
      ...doc(
        `Unwrap a \`${rname}\` for the wire.\n\nOne of the two places a §27 secret is unwrapped, so that "put a secret on the socket" stays a single greppable call rather than fourteen (§7 rule 4).`,
      ),
    );
    lines.push(`export function ${camel(rname)}ToWire(v: ${rname}): ${wire} {`);
    lines.push('  return {');
    lines.push('    ...v,');
    for (const f of fields.filter((x) => x.secret)) {
      lines.push(
        f.optional
          ? `    ${f.name}: v.${f.name} === undefined ? undefined : v.${f.name}.expose(),`
          : `    ${f.name}: v.${f.name}.expose(),`,
      );
    }
    lines.push('  };');
    lines.push('}');
    lines.push('');
  }
  return lines.join('\n');
}

