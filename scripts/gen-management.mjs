files.set(join(ROOT, 'src/management/ops/index.ts'), emitOpsIndex());
files.set(join(ROOT, 'test/management.surface.generated.test.ts'), emitTest());

const check = process.argv.includes('--check');
if (check) {
  const stale = [...files].filter(
    ([p, body]) => !existsSync(p) || readFileSync(p, 'utf8') !== body,
  );
  if (stale.length) {
    for (const [p] of stale) console.error(`FAIL: ${relative(ROOT, p)} is stale`);
    console.error('run `node scripts/gen-management.mjs`');
    process.exit(1);
  }
  console.log(
    `OK: ${files.size} generated files are current (${REGISTRY.operation_count} operations)`,
  );
} else {
  for (const [p, body] of files) {
    mkdirSync(dirname(p), { recursive: true });
    writeFileSync(p, body.endsWith('\n') ? body : `${body}\n`);
  }
  console.log(
    `wrote ${files.size} files: ${REGISTRY.operation_count} operations across ${REGISTRY.namespace_count} namespaces`,
  );
}
