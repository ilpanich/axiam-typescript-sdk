const pascal = (s) => {
  const p = s.split(/[_\-\s]+/).filter(Boolean).map((x) => x[0].toUpperCase() + x.slice(1)).join('');
  return RENAMED_SCHEMAS[p] ?? p;
};
const camel = (s) => {
  const p = pascal(s);
  return p[0].toLowerCase() + p.slice(1);
};

/** Reflow a paragraph; TypeScript formatters do not reflow comments either. */
function wrap(text, width = 74) {
  const out = [];
  for (const para of String(text).trim().split(/\n\n+/)) {
    const words = para.split(/\s+/).filter(Boolean);
    if (!words.length) continue;
    let line = '';
    for (const word of words) {
      if (line && line.length + 1 + word.length > width) {
        out.push(line);
        line = word;
      } else {
        line = line ? `${line} ${word}` : word;
      }
    }
    if (line) out.push(line);
    out.push('');
  }
  while (out.length && out.at(-1) === '') out.pop();
  return out;
}

/** A JSDoc block, or nothing when there is no text. */
function doc(text, indent = '') {
  if (!text) return [];
  const lines = wrap(text);
  if (lines.length === 1) return [`${indent}/** ${lines[0]} */`];
  return [
    `${indent}/**`,
    ...lines.map((l) => (l ? `${indent} * ${l}` : `${indent} *`)),
    `${indent} */`,
  ];
}

