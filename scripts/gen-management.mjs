function emitOpsIndex() {
  const names = Object.keys(REGISTRY.namespaces);
  const lines = [
    BANNER,
    '/**',
    ' * One handle per §27 namespace, and the accessors that reach them.',
    ' *',
    ' * §27.2 makes this namespacing normative rather than stylistic: twenty',
    ' * namespaces have a `list` and fourteen a `get`, so flattening 147 operations',
    ' * onto the client would need a disambiguating prefix invented once per',
    ' * operation — and would bury the eight §1 methods most callers actually want',
    ' * under five times as many they do not.',
    ' */',
    '',
  ];
  for (const ns of names) lines.push(`export * from './${ns}.js';`);
  lines.push('');
  for (const ns of names) {
    lines.push(`import { ${pascal(ns)}Api } from './${ns}.js';`);
  }
  lines.push("import type { AxiamClient } from '../../rest/client.js';");
  lines.push('');
  lines.push(...doc('Every §27 namespace handle, lazily constructed per access.'));
  lines.push('export interface ManagementNamespaces {');
  for (const ns of names) {
    lines.push(...doc(REGISTRY.namespaces[ns].doc, '  '));
    lines.push(`  readonly ${camel(ns)}: ${pascal(ns)}Api;`);
  }
  lines.push('}');
  lines.push('');
  lines.push(
    ...doc(
      'Build the namespace handles for `client`.\n\n@internal — reached as `client.users`, `client.roles`, and so on.',
    ),
  );
  lines.push('export function managementNamespaces(client: AxiamClient): ManagementNamespaces {');
  lines.push('  return {');
  for (const ns of names) {
    lines.push(`    get ${camel(ns)}() {`);
    lines.push(`      return new ${pascal(ns)}Api(client);`);
    lines.push('    },');
  }
  lines.push('  };');
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

