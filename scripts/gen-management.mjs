#!/usr/bin/env node
// Generate the CONTRACT §27 management surface for the TypeScript SDK.
//
// Reads the two vendored artifacts — `management-registry.json` (the normative
// §27 vocabulary) and `openapi.json` (the schemas it refers to) — and writes:
//
//     src/management/models.ts               request/response types
//     src/management/ops/<namespace>.ts      one handle per namespace
//     src/management/ops/index.ts
//     test/management.surface.generated.test.ts
//
// §27.8 draws the line this script works to: the models and the raw calls are
// generated, everything ergonomic is not. Nothing here builds a client or maps
// an error — every generated call goes through `sendManagement`, so §3 (CSRF),
// §4 (the cookie jar), §5 (X-Tenant-ID), §9 (single-flight refresh), §16 and
// §19 are inherited from the shared axios instance rather than reimplemented
// 147 times.
//
// The generated test matters as much as the generated code. This repo's
// coverage floor is 94% of lines and 95% of functions, and 147 hand-written
// smoke tests is the chore that gets three-quarters done.
//
//   node scripts/gen-management.mjs            # write
//   node scripts/gen-management.mjs --check    # verify committed output

import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const REGISTRY = JSON.parse(readFileSync(join(ROOT, 'management-registry.json'), 'utf8'));
const SPEC = JSON.parse(readFileSync(join(ROOT, 'openapi.json'), 'utf8'));
const SCHEMAS = SPEC.components.schemas;

const BANNER = `// @generated by scripts/gen-management.mjs from management-registry.json and
// openapi.json. DO NOT EDIT — your changes will be overwritten. Regenerate with
// \`node scripts/gen-management.mjs\`; CI verifies the committed output is current.
`;

// §27.4 rule 3: `{org_id}` always defaults from the client. `{tenant_id}`
// defaults from the client only where it names the *context*; in `tenants` and
// the signing-CA routes it names the object being acted on.
const IMPLICIT_TENANT_NAMESPACES = new Set(['email_config', 'settings', 'webauthn_policy']);

// ---------------------------------------------------------------------------
// Naming
// ---------------------------------------------------------------------------

// Schema names that would collide with a type this SDK already exports. The
// generated surface is re-exported from the package root, so a duplicate name
// makes one of the two unreachable — and the one that loses is whichever the
// barrel happens to list second.
const RENAMED_SCHEMAS = {
  // §23's `OpaqueEnrollment` (src/rest/opaque.ts) is the enrolment *result* a
  // caller receives; this is the registration payload a caller *sends* when
  // creating a user. Different shapes, same server-side vocabulary.
  OpaqueEnrollment: 'OpaqueEnrollmentPayload',
};

const pascal = (s) => {
  const p = s.split(/[_\-\s]+/).filter(Boolean).map((x) => x[0].toUpperCase() + x.slice(1)).join('');
  return RENAMED_SCHEMAS[p] ?? p;
};
const camel = (s) => {
  const p = pascal(s);
  return p[0].toLowerCase() + p.slice(1);
};

/** Reflow a paragraph; TypeScript formatters do not reflow comments either. */
function wrap(text, width = 74) {
  const out = [];
  for (const para of String(text).trim().split(/\n\n+/)) {
    const words = para.split(/\s+/).filter(Boolean);
    if (!words.length) continue;
    let line = '';
    for (const word of words) {
      if (line && line.length + 1 + word.length > width) {
        out.push(line);
        line = word;
      } else {
        line = line ? `${line} ${word}` : word;
      }
    }
    if (line) out.push(line);
    out.push('');
  }
  while (out.length && out.at(-1) === '') out.pop();
  return out;
}

/** A JSDoc block, or nothing when there is no text. */
function doc(text, indent = '') {
  if (!text) return [];
  const lines = wrap(text);
  if (lines.length === 1) return [`${indent}/** ${lines[0]} */`];
  return [
    `${indent}/**`,
    ...lines.map((l) => (l ? `${indent} * ${l}` : `${indent} *`)),
    `${indent} */`,
  ];
}

