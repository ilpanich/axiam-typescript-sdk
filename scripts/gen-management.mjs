// Generate the CONTRACT §27 management surface for the TypeScript SDK.
//
// Reads the two vendored artifacts — `management-registry.json` (the normative
// §27 vocabulary) and `openapi.json` (the schemas it refers to) — and writes:
//
//     src/management/models.ts               request/response types
//     src/management/ops/<namespace>.ts      one handle per namespace
//     src/management/ops/index.ts
//     test/management.surface.generated.test.ts
//
// §27.8 draws the line this script works to: the models and the raw calls are
// generated, everything ergonomic is not. Nothing here builds a client or maps
// an error — every generated call goes through `sendManagement`, so §3 (CSRF),
// §4 (the cookie jar), §5 (X-Tenant-ID), §9 (single-flight refresh), §16 and
// §19 are inherited from the shared axios instance rather than reimplemented
// 190 times.
//
// The generated test matters as much as the generated code. This repo's
// coverage floor is 94% of lines and 95% of functions, and 190 hand-written
// smoke tests is the chore that gets three-quarters done.
//
//   node scripts/gen-management.mjs            # write
//   node scripts/gen-management.mjs --check    # verify committed output

