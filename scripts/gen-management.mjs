const resolveRef = (schema) => {
  let s = schema;
  while (s && s.$ref) s = SCHEMAS[s.$ref.split('/').pop()];
  return s;
};

/** `{oneOf: [{type:null}, {$ref: X}]}` — utoipa's optional-enum shape. */
function nullableRef(schema) {
  const variants = schema?.oneOf;
  if (!Array.isArray(variants) || variants.length !== 2) return null;
  const nulls = variants.filter((v) => v.type === 'null');
  const refs = variants.filter((v) => v.$ref);
  return nulls.length === 1 && refs.length === 1 ? refs[0].$ref.split('/').pop() : null;
}

function tsType(schema) {
  if (!schema || Object.keys(schema).length === 0) return 'unknown';
  if (schema.$ref) return pascal(schema.$ref.split('/').pop());
  const inner = nullableRef(schema);
  if (inner) return `${pascal(inner)} | null`;
  if (schema.oneOf || schema.anyOf) return 'unknown';

  let t = schema.type;
  let nullable = false;
  if (Array.isArray(t)) {
    nullable = t.includes('null');
    t = t.find((x) => x !== 'null');
  }
  let base;
  if (schema.enum) base = schema.enum.map((v) => JSON.stringify(v)).join(' | ');
  else if (t === 'string') base = 'string';
  else if (t === 'integer' || t === 'number') base = 'number';
  else if (t === 'boolean') base = 'boolean';
  else if (t === 'array') {
    const item = tsType(schema.items ?? {});
    base = /[|&]/.test(item) ? `Array<${item}>` : `${item}[]`;
  } else if (t === 'object') base = 'Record<string, unknown>';
  else base = 'unknown';
  return nullable ? `${base} | null` : base;
}

/** Properties + required set of a component schema, `allOf` resolved. */
function flatten(name) {
  const schema = SCHEMAS[name];
  const props = {};
  const required = new Set();
  const absorb = (node) => {
    const n = node.$ref ? resolveRef(node) : node;
    Object.assign(props, n.properties ?? {});
    for (const r of n.required ?? []) required.add(r);
    for (const sub of n.allOf ?? []) absorb(sub);
  };
  absorb(schema);
  return { props, required, description: schema.description };
}

/** Every schema `name` inherits from via `allOf`, transitively. */
function composedFrom(name, seen = new Set()) {
  if (seen.has(name)) return new Set();
  const out = new Set();
  for (const sub of SCHEMAS[name]?.allOf ?? []) {
    if (sub.$ref) {
      const parent = sub.$ref.split('/').pop();
      out.add(parent);
      for (const p of composedFrom(parent, new Set([...seen, name]))) out.add(p);
    }
  }
  return out;
}

/** Detect an internally-tagged union; both on this surface have that shape. */
function discriminated(schema) {
  const variants = schema.oneOf;
  if (!Array.isArray(variants) || variants.length < 2) return null;
  let tag = null;
  const arms = [];
  for (const variant of variants) {
    const parts = variant.allOf ?? [variant];
    let value = null;
    let payload = null;
    const leftovers = { type: 'object', properties: {}, required: [] };
    for (const part of parts) {
      if (part.$ref) {
        payload = part;
        continue;
      }
      for (const [name, prop] of Object.entries(part.properties ?? {})) {
        if (prop.type === 'string' && Array.isArray(prop.enum) && prop.enum.length === 1) {
          if (tag && tag !== name) return null;
          tag = name;
          value = prop.enum[0];
        } else {
          leftovers.properties[name] = prop;
          if ((part.required ?? []).includes(name)) leftovers.required.push(name);
        }
      }
    }
    if (value === null) return null;
    arms.push({ value, payload: payload ?? leftovers });
  }
  return { tag, arms };
}

/**
 * Detect an **externally-tagged** `oneOf` — a union with no shared
 * discriminator field, where each variant is instead a single-key object
 * (`{"dns": "…"}` | `{"ip": "…"}`, `SubjectAltName`'s shape, contract 1.51).
 *
 * `discriminated()` above only recognises the *internally*-tagged shape
 * (`{"kind": "dns", ...}`), so this one fell through it to `emitInterface`,
 * whose `flatten()` finds no top-level `properties` and no `allOf` on a bare
 * `oneOf` schema — producing an interface with **no fields at all**, which
 * compiles, and which serializes as `{}`. The server refuses `{}`. This is
 * the TypeScript shape of the defect the Rust reference's re-vendor found in
 * its own generator (C-1 EXECUTED item 2).
 *
 * Returns one `{ key, schema, description }` per variant, or `null` when the
 * shape does not match (every variant a single-key required object, one key
 * per variant) — never a false positive on `discriminated()`'s shape, which
 * is checked first by the caller.
 */
function externallyTagged(schema) {
  const variants = schema.oneOf;
  if (!Array.isArray(variants) || variants.length < 2) return null;
  const arms = [];
  for (const v of variants) {
    if (v.$ref || v.type !== 'object') return null;
    const required = v.required ?? [];
    const propNames = Object.keys(v.properties ?? {});
    if (required.length !== 1 || propNames.length !== 1 || propNames[0] !== required[0]) {
      return null;
    }
    const key = required[0];
    arms.push({ key, schema: v.properties[key], description: v.description ?? schema.description });
  }
  return arms;
}

function emitExternallyTagged(rname, schema, arms) {
  const lines = doc(
    (schema.description ?? `\`${rname}\` — externally tagged by its single present key.`) +
      `\n\nEach variant is a plain object naming exactly one field; there is no shared ` +
      `discriminator. Build a literal (\`{ ${arms[0].key}: … }\`) rather than a helper — ` +
      'there is nothing to construct beyond the object itself.',
  );
  lines.push(`export type ${rname} =`);
  arms.forEach(({ key, schema: s, description }, i) => {
    const tail = i === arms.length - 1 ? ';' : '';
    lines.push('  | {');
    lines.push(...doc(description ?? `\`${key}\`.`, '      '));
    lines.push(`      ${key}: ${tsType(s)};`);
    lines.push(`    }${tail}`);
  });
  lines.push('');

  const keys = arms.map((a) => a.key);
  const keyList = keys.map((k) => `'${k}'`).join(', ');
  lines.push(
    ...doc(
      `Refuse a \`${rname}\` naming neither or both of ${keyList} (CONTRACT.md §27.13, ` +
        `CONTRACT 1.52 N3, C-12). \`${rname}\` is externally tagged — a plain object with ` +
        `no shared discriminator — so the TypeScript union above does not itself stop a ` +
        `dynamically-built value from holding neither key or both; TypeScript's excess` +
        `-property check only fires on an object LITERAL assigned directly, never on a ` +
        `value built up field-by-field or passed through a variable. The server accepts ` +
        `exactly one key; a value with zero or two is refused client-side, before any ` +
        `request (§27.4 rule 2's error), rather than silently dropped or sent malformed.`,
    ),
  );
  lines.push(`export function assertValid${rname}(value: ${rname}): void {`);
  lines.push(`  const present = [${keyList}].filter(`);
  lines.push(`    (k) => (value as unknown as Record<string, unknown>)[k] !== undefined,`);
  lines.push('  );');
  lines.push('  if (present.length !== 1) {');
  lines.push('    throw new NetworkError(');
  lines.push(
    `      \`${rname} must have exactly one of ${keys.join(', ')} (CONTRACT.md §27.4 rule 2); got \${JSON.stringify(value)}\`,`,
  );
  lines.push('    );');
  lines.push('  }');
  lines.push('}');
  lines.push('');
  lines.push(...doc(`Runs {@link assertValid${rname}} over every element of a possibly-absent \`${rname}[]\` (CONTRACT 1.52 N3, C-12). A \`null\`/\`undefined\` list is left alone — there is nothing to validate.`));
  lines.push(`export function assertValid${rname}List(values: ${rname}[] | null | undefined): void {`);
  lines.push('  if (!values) return;');
  lines.push(`  for (const value of values) assertValid${rname}(value);`);
  lines.push('}');
  lines.push('');
  return lines.join('\n');
}

