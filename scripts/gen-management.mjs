const EXAMPLE_UUID = '11111111-1111-4111-8111-111111111111';
const EXAMPLE_TIME = '2026-08-26T00:00:00Z';

function exampleJson(schema, depth = 0) {
  if (depth > 6 || !schema) return null;
  if (schema.$ref) return exampleJson(resolveRef(schema), depth + 1);
  const inner = nullableRef(schema);
  if (inner) return exampleJson(SCHEMAS[inner], depth + 1);
  if (schema.enum) return schema.enum[0];
  const variants = schema.oneOf ?? schema.anyOf;
  if (variants) {
    const first = variants.find((v) => v.type !== 'null');
    return first ? exampleJson(first, depth + 1) : null;
  }
  if (schema.allOf) {
    return schema.allOf.reduce((acc, part) => {
      const got = exampleJson(part, depth + 1);
      return got && typeof got === 'object' ? { ...acc, ...got } : acc;
    }, {});
  }
  let t = schema.type;
  if (Array.isArray(t)) t = t.find((x) => x !== 'null');
  if (t === 'object' || (!t && schema.properties)) {
    const required = new Set(schema.required ?? []);
    const out = {};
    for (const [name, prop] of Object.entries(schema.properties ?? {})) {
      if (required.has(name)) out[name] = exampleJson(prop, depth + 1);
    }
    return out;
  }
  if (t === 'array') return [];
  if (t === 'integer' || t === 'number') return 1;
  if (t === 'boolean') return true;
  if (t === 'string') {
    if (schema.format === 'uuid') return EXAMPLE_UUID;
    if (schema.format === 'date-time') return EXAMPLE_TIME;
    return 'example';
  }
  return {};
}

function exampleResponse(op) {
  const { kind, schema } = op.response;
  if (kind === 'none') return 'undefined';
  const one = exampleJson(SCHEMAS[schema]);
  if (kind === 'array') return JSON.stringify([one]);
  if (kind === 'page') {
    return JSON.stringify({ items: [one], total: 1, offset: 0, limit: 50 });
  }
  return JSON.stringify(one);
}

/** A TypeScript expression building a minimal valid value for a schema. */
function tsLiteral(schema, secrets, field = null, depth = 0) {
  if (depth > 6) return 'undefined';
  if (field && secrets.has(field)) return "new Sensitive('example')";
  if (schema.$ref) return literalFor(schema.$ref.split('/').pop(), secrets, depth + 1);
  if (nullableRef(schema)) return 'undefined';
  if (schema.oneOf || schema.anyOf) return 'undefined';
  let t = schema.type;
  if (Array.isArray(t) && t.includes('null')) return 'undefined';
  if (Array.isArray(t)) t = t.find((x) => x !== 'null');
  if (schema.enum) return JSON.stringify(schema.enum[0]);
  if (t === 'array') return '[]';
  if (t === 'integer' || t === 'number') return '1';
  if (t === 'boolean') return 'true';
  if (t === 'string') {
    if (schema.format === 'uuid') return `'${EXAMPLE_UUID}'`;
    if (schema.format === 'date-time') return `'${EXAMPLE_TIME}'`;
    return "'example'";
  }
  if (t === 'object' || !Object.keys(schema).length) return '{}';
  return 'undefined';
}

function literalFor(name, secrets, depth = 0) {
  const schema = SCHEMAS[name] ?? {};
  if (schema.enum) return JSON.stringify(schema.enum[0]);
  if (schema.oneOf) {
    const union = discriminated(schema);
    if (union) {
      const { value, payload } = union.arms[0];
      if (payload.$ref) {
        const inner = literalFor(payload.$ref.split('/').pop(), secrets, depth + 1);
        return `{ ${union.tag}: ${JSON.stringify(value)}, ...${inner} }`;
      }
      // An inline arm (contract 1.58's `ScimTargetAuth` / `ScimTargetScope`):
      // the tag plus the arm's own required members.
      const required = new Set(payload.required ?? []);
      const members = Object.entries(payload.properties ?? {})
        .filter(([p]) => required.has(p))
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([p, ps]) => `${p}: ${tsLiteral(ps, new Set(), p, depth + 1)}`);
      return `{ ${[`${union.tag}: ${JSON.stringify(value)}`, ...members].join(', ')} }`;
    }
    return 'undefined';
  }
  const { props, required } = flatten(name);
  const own = depth === 0 ? secrets : new Set();
  const parts = Object.keys(props)
    .sort()
    .filter((p) => required.has(p))
    .map((p) => `${p}: ${tsLiteral(props[p], own, p, depth + 1)}`);
  return `{ ${parts.join(', ')} }`;
}

function callArguments(namespace, opname, op, secrets) {
  const implicit = implicitParams(namespace, op);
  const args = [];
  let route = op.path;
  for (const p of op.path_params) {
    if (implicit.has(p.name)) {
      route = route.replace(`{${p.name}}`, p.name === 'org_id' ? '${ORG_ID}' : '${TENANT_ID}');
      continue;
    }
    if (p.format === 'uuid') {
      args.push('EXAMPLE_ID');
      route = route.replace(`{${p.name}}`, '${EXAMPLE_ID}');
    } else {
      args.push("'example'");
      route = route.replace(`{${p.name}}`, 'example');
    }
  }
  const extra = extraQueryParams(op);
  const requiredQ = extra.filter((q) => q.required);
  const optionalQ = extra.filter((q) => !q.required);
  for (const _ of requiredQ) args.push("'example'");
  if (optionalQ.length > 2) args.push('{}');
  else for (const _ of optionalQ) args.push('undefined');
  if (op.paginated) args.push('{ limit: 50 }');
  if (op.request_body === 'schema' && PRECHECK_TEST_BODIES[`${namespace}.${opname}`]) {
    args.push(PRECHECK_TEST_BODIES[`${namespace}.${opname}`]);
  } else if (op.request_body === 'schema') {
    args.push(literalFor(op.request_schema, secrets.get(op.request_schema) ?? new Set()));
  } else if (op.request_body === 'untyped') {
    args.push('{}');
  }
  return { args, route };
}

